/**
 ******************************************************************************
 *  502 步骤 12：LED 专项测试（红 / 黄 分开亮，每个 2 秒）
 ******************************************************************************
 *  为什么单独做一个：
 *      10_selftest 里声光自检是「红 120ms + 黄 120ms」一闪而过，
 *      很容易看不清到底是哪个不亮。这里每个灯亮 2 秒，肉眼绝对分得清。
 *
 *  接线：
 *      红 LED：PB1 → 220Ω → LED 长脚(+)；短脚(−) → GND
 *      黄 LED：PB5 → 220Ω → LED 长脚(+)；短脚(−) → GND
 *
 *  顺序：红 2s → 黄 2s → 两个一起 2s → 全灭 1s（循环）
 *  串口同步打印当前状态，可直接对照。
 ******************************************************************************
 */
#include "bsp.h"
#include "app502.h"

static void show(int r, int y, const char *msg)
{
    led_red(r);
    led_yellow(y);
    printf("[LED] 红=%d 黄=%d  %s\r\n", r, y, msg);
}

int main(void)
{
    bsp_init();
    app502_init();
    uart1_init();

    printf("\r\n========================================\r\n");
    printf("  502 LED 测试（每个亮 2 秒）\r\n");
    printf("  红：PB1  黄：PB5  都串 220Ω\r\n");
    printf("========================================\r\n");

    while (1) {
        show(1, 0, "只有【红】应亮");
        delay_ms(2000);

        show(0, 0, "全灭");
        delay_ms(400);

        show(0, 1, "只有【黄】应亮");
        delay_ms(2000);

        show(0, 0, "全灭");
        delay_ms(400);

        show(1, 1, "【红+黄】应同时亮");
        delay_ms(2000);

        show(0, 0, "全灭");
        delay_ms(1000);
    }
}
