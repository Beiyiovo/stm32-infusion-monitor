/**
 ******************************************************************************
 *  drop.h —— 滴速检测（红外对射 + 外部中断）
 ******************************************************************************
 *  接线：接收头 OUT → PB12（上拉输入），发射头 2 针接 3V3/GND
 *  原理：每落一滴，红外光被遮断一次 → PB12 产生一个下降沿 → 中断里计数
 *  ★ 局限：液滴"成线"时没有离散跳变，光学方法数不到 —— 报告里要写清楚
 ******************************************************************************
 */
#ifndef __DROP_H
#define __DROP_H

#include "bsp.h"
#include "app502.h"

#define DROP_WINDOW_MS      10000U      /* 统计窗口：10 秒 */
#define DROP_DEBOUNCE_MS    30U         /* 两滴最小间隔（≈2000 滴/分，防抖） */

void     drop_init(void);               /* PB12 + EXTI12 初始化 */
void     drop_reset(void);              /* 清计数与窗口 */
void     drop_tick(void);               /* ★ 主循环必须周期性调用（≥10Hz） */
uint16_t drop_window_drops(void);       /* 当前窗口内已计滴数 */
float    drop_rate_dpm(void);           /* 最近一个完整窗口的 滴/分 */
uint32_t drop_total(void);              /* 上电以来的累计滴数 */

#endif /* __DROP_H */
