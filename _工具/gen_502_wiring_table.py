        '上面标 ★ 的 6 条，都是项目1 在真实硬件上踩出来的结论，本项目原样照搬，不重新发明。',
        '标 ⚠ 的 2 条（HX711、红外模块）没有上板验证过，到货后按《面包板接线与通电验收单》先验。',
