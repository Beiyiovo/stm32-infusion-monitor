def pic(doc, rel, width_cm, caption=None):
    p = os.path.join(BASE, rel)
    if not os.path.exists(p):
        para(doc, f"（缺图：{rel}）", size=9, color=RED)
        return
    doc.add_picture(p, width=Cm(width_cm))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.paragraphs[-1].paragraph_format.space_before = Pt(4)
    doc.paragraphs[-1].paragraph_format.space_after = Pt(2)
    if caption:
        para(doc, caption, size=8.5, color=GREY, align='center', space_after=8)


